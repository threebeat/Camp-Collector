async function crop(im, rect, width, height) {
 const [x,y,w,h]=rect, c=createCanvas(width,height),ctx=c.getContext('2d');
 ctx.imageSmoothingEnabled=false;
 const scale=Math.min((width-6)/w,(height-6)/h), dw=Math.round(w*scale), dh=Math.round(h*scale);
 ctx.drawImage(im,x,y,w,h,Math.round((width-dw)/2),height-dh-3,dw,dh);
 return await c.encode('png');
}
