// Slice and package the generated source atlases without repainting their art.
// Run after editing the checked-in source files in assets/ruin-source/.
import { createCanvas, loadImage } from '@napi-rs/canvas';
import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { resolve } from 'node:path';
const root = resolve(import.meta.dirname, '..');
const source = resolve(root, 'assets/ruin-source');
const out = resolve(root, 'web');
await mkdir(source, {recursive: true});
const uri = (b, type='png') => 'data:image/'+type+';base64,' + b.toString('base64');
function envelope(bytes, w, h, type='png') { return `<svg xmlns="http://www.w3.org/2000/svg" width="${w}" height="${h}" viewBox="0 0 ${w} ${h}"><image width="${w}" height="${h}" href="${uri(bytes,type)}"/></svg>`; }
async function packageImage(file, name, maxWidth) {
  const im = await loadImage(resolve(source,file)), w = Math.min(im.width,maxWidth), h = Math.round(im.height*w/im.width);
  const c=createCanvas(w,h),ctx=c.getContext('2d');ctx.imageSmoothingEnabled=false;ctx.drawImage(im,0,0,w,h);
  const bytes=await c.encode('webp',88);await writeFile(resolve(out,name+'.webp'),bytes);await writeFile(resolve(out,name+'.svg'),envelope(bytes,w,h,'webp'));
}
await packageImage('camp.webp','map-camp-v07',1468);
